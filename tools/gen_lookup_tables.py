#!/usr/bin/env python3
"""Generate core/lookup_tables.inc, the word lookup's two tables, from tools/lookup_tables.txt.

tools/lookup_tables.txt is the one source of preferred_readings and usual_spellings: the reader
(core/local_dict.c rank_posting) includes this generated file, and the converter
(tools/convert_dictionary.py lookup_tables, table_bits) reads the text file itself to mark, in a
file with table hints (hints version 2, docs/local-dictionaries.md), each key's entry that a table
names. Both name the tables by the same id (convert_dictionary.tables_id): a file's table bits are
used only by a reader built from the same tables. The arrays stay in the Shell's data segment
(VJO_DATA_TABLE, core/port.h), byte for byte as they were written in local_dict.c.

    python3 tools/gen_lookup_tables.py      # after an edit of tools/lookup_tables.txt
"""
from pathlib import Path

import convert_dictionary as convert

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "core/lookup_tables.inc"
LINE_CHARS = 64  # characters of one C string literal line (each "\0" counts 2)


def literal(data):
    """data (bytes: UTF-8 text and NULs) as the body of a C string literal. A NUL is "\\0", or "\\000"
    before an octal digit, which "\\0" would take into its escape; the table has no quote, backslash
    or question mark (convert_dictionary.lookup_tables refuses them), so nothing else is escaped."""
    text, out = data.decode("utf-8"), []
    for i, char in enumerate(text):
        if char == "\0":
            out.append("\\000" if i + 1 < len(text) and text[i + 1] in "01234567" else "\\0")
        else:
            out.append(char)
    return "".join(out)


def array(name, pairs):
    """One table as the C array local_dict.c had: its pairs, a few to a line, and the empty key that
    ends it (the literal's own NUL)."""
    lines, line = [], ""
    for key, value in pairs.items():
        piece = literal(key + b"\0" + value + b"\0")
        if line and len(line) + len(piece) > LINE_CHARS:
            lines.append(line)
            line = ""
        line += piece
    lines.append(line)
    body = "\n".join(f'    "{part}"' for part in lines)
    return f"static const char {name}[] VJO_DATA_TABLE({name}) =\n{body};"


def generate(tables=None):
    tables = convert.lookup_tables() if tables is None else tables
    parts = ["/* Generated by tools/gen_lookup_tables.py from tools/lookup_tables.txt, which says what each table",
             " * is for; do not edit by hand. A table is its pairs, key then value, each NUL terminated, and an",
             " * empty key ends it. */"]
    parts.extend(array(name, tables[name]) for name in convert.TABLE_NAMES)
    parts.extend(["/* The tables' id (tools/convert_dictionary.py tables_id: FNV-1a-32 of both arrays' bytes): page 0",
                  " * of a file with hints version 2 names the tables its postings' table bits were made with. */",
                  f"#define LOOKUP_TABLES_ID 0x{convert.tables_id(tables):08x}u", ""])
    return "\n".join(parts)


if __name__ == "__main__":
    OUTPUT.write_text(generate(), encoding="utf-8")
