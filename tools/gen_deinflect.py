#!/usr/bin/env python3
"""Generate the immutable C suffix table from the vendored Yomichan rules and Yomitan's supplement.

third_party/yomichan/deinflect.json (FooSoft/Yomichan) is the base; third_party/yomitan/
deinflect-supplement.json (tools/yomitan_check/port_yomitan_rules.mjs) removes the rules
Yomitan no longer has and adds the suffix rules of the transforms the old table lacks, with
Rubi's own long-vowel forms ("rubi"). Labels keep their order, a label left without rules is
dropped, and new ones follow; a reason's number lives only in one lookup's tokens and locators,
never on storage, so the numbers may change with the table.

The table is small because the Shell's pages are (docs/memory-ledger.md): every rule string is
three-byte UTF-8, so their BMP codepoints fit in uint16_t. They are packed without NULs, each
string sharing characters of another that contains it or overlaps its end. A rule is six bytes: its strings'
offsets and lengths in characters, its reason (the conjugation label) and its rule bits.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULES = {"v1": 1, "v5": 2, "vs": 4, "vk": 8, "vz": 16, "adj-i": 32, "iru": 64}
OFFSET_BITS, CHARS_BITS = 11, 5  # offsets and lengths in characters, one u16 each
RULES_IN_SLOTS, MAX_LABELS = 8, 62  # three bits of input rule-bit sets; six-bit reasons, 0 and 63 taken


def check(ok, what):
    """A table limit, checked even under python -O (an assert would vanish and the table be wrong)."""
    if not ok:
        raise SystemExit(f"gen_deinflect.py: {what}")


def rule_sets():
    """{label: [rule]}: the old rules less the supplement's removals, then its additions."""
    data = json.loads((ROOT / "third_party/yomichan/deinflect.json").read_text())
    supplement = json.loads((ROOT / "third_party/yomitan/deinflect-supplement.json").read_text())
    for gone in supplement["remove"]:
        rules = data[gone["reason"]]
        kept = [r for r in rules if (r["kanaIn"], r["kanaOut"]) != (gone["kanaIn"], gone["kanaOut"])]
        check(len(kept) == len(rules) - 1, f"the supplement removes a rule the table does not have once: {gone}")
        data[gone["reason"]] = kept
    for part in ("add", "rubi"):
        for label, rules in supplement[part].items():
            data.setdefault(label, []).extend(rules)
    return {label: rules for label, rules in data.items() if rules}


def pack(strings):
    """One blob holding every string, and each string's character offset in it."""
    encoded = sorted({s.encode() for s in strings if s}, key=lambda b: (-len(b), b))
    pieces = [e for i, e in enumerate(encoded) if not any(e in o for o in encoded[:i])]
    while len(pieces) > 1:  # greedy: merge the two pieces that overlap most (ties: first pair)
        best = (0, 0, 1)
        for i, a in enumerate(pieces):
            for j, b in enumerate(pieces):
                if i != j:
                    k = next((k for k in range(min(len(a), len(b)) - 1, 0, -1) if a.endswith(b[:k])), 0)
                    if k > best[0]:
                        best = (k, i, j)
        k, i, j = best
        if not k:
            break
        merged = pieces[i] + pieces[j][k:]
        pieces = [p for t, p in enumerate(pieces) if t not in (i, j)] + [merged]
    blob = b"".join(pieces)
    offsets = {}
    for s in strings:
        b = s.encode()
        at = blob.find(b) if b else 0
        check(at >= 0 and at % 3 == 0, f"{s!r} is not at a whole character of the packed strings")
        offsets[s] = at // 3
    return blob, offsets


def generate():
    data = rule_sets()
    lines = ["/* Generated by tools/gen_deinflect.py; Yomichan's GPL-3.0 and Yomitan's GPL-3.0-or-later rules.",
             " * See third_party/yomichan/README.md and third_party/yomitan/README.md. Do not edit by hand. */"]
    # Matching suffixes must end in the same UTF-8 byte. Stable grouping keeps
    # candidate order unchanged while avoiding a scan of every rule. Every rule string ends in a
    # three-byte character (checked below), so in a continuation byte, 0x80-0xBF: 64 buckets.
    buckets = [[] for _ in range(64)]
    check(len(data) <= MAX_LABELS, f"{len(data)} labels, more than the {MAX_LABELS} six-bit reasons (0 = exact, 63 = ellipsis)")
    rules_in = []
    for reason, rules in enumerate(data.values(), 1):
        for rule in rules:
            check(all(len(c.encode()) == 3 for c in rule["kanaIn"] + rule["kanaOut"]),
                  f"a rule string not all three-byte UTF-8: {rule}")
            check(0 < len(rule["kanaIn"]) < 1 << CHARS_BITS and len(rule["kanaOut"]) < 1 << CHARS_BITS,
                  f"a rule string of 0 or {1 << CHARS_BITS} or more characters: {rule}")
            flags = [sum(RULES[r] for r in rule[key]) for key in ("rulesIn", "rulesOut")]
            if flags[0] not in rules_in:
                rules_in.append(flags[0])
            buckets[rule["kanaIn"].encode()[-1] - 0x80].append((rule, reason, flags))
    check(len(rules_in) <= RULES_IN_SLOTS, f"{len(rules_in)} distinct input rule-bit sets, more than {RULES_IN_SLOTS}")
    blob, offsets = pack([r["kanaIn"] for b in buckets for r, _, _ in b] + [r["kanaOut"] for b in buckets for r, _, _ in b])
    check(len(blob) // 3 < 1 << OFFSET_BITS,
          f"the packed strings are {len(blob) // 3} characters, {1 << OFFSET_BITS} or more (an 11-bit offset)")
    text = blob.decode()
    lines.append("/* BMP codepoints: two bytes each instead of three-byte UTF-8; offsets stay in characters. */")
    lines.append("static const uint16_t deinflect_strings[] = {")
    lines.extend("    " + ", ".join(f"0x{ord(c):04x}" for c in text[i:i + 12]) + ","
                 for i in range(0, len(text), 12))
    # Yomichan's one-step causative passive (買わされる -> 買う) counts as the two steps it contracts
    # (causative and passive, as Yomitan, which has no such rule, reaches it): a one-step reading
    # of the same text wins over it (かわされた: 交わす, passive, not 買う; #321).
    lines.extend(["};", "/* The reason whose rules count two steps (core/local_dict.c deinflect). */",
                  "#define DEINFLECT_TWO_STEPS %du" % (list(data).index("causative passive") + 1)])
    lines.extend(["/* A rule's input bits, by the index in its bits' top three. */",
                  "static const uint8_t deinflect_rules_in[%d] = {%s};" % (len(rules_in), ", ".join(map(str, rules_in))),
                  "/* In the data segment: the Shell's code pages are full, its data pages are not (docs/memory-ledger.md). */",
                  "static const DeinflectRule deinflect_rules[] VJO_DATA_TABLE(deinflect_rules) = {"])
    offsets_table, count = [], 0
    for bucket in buckets:
        offsets_table.append(count)
        for rule, reason, (flags_in, flags_out) in bucket:
            source, target = rule["kanaIn"], rule["kanaOut"]
            check(flags_out <= 127, f"output rule bits past seven bits: {rule}")
            lines.append("    {%d, %d, %d}," % (
                offsets[source] | len(source) << OFFSET_BITS, offsets[target] | len(target) << OFFSET_BITS,
                reason | flags_out << 6 | rules_in.index(flags_in) << 13))
            count += 1
    offsets_table.append(count)
    lines.extend(["};", "/* A key whose last byte is 0x80 + i (a continuation byte) has rules i's: from offset i to i + 1. */",
                  "static const uint16_t deinflect_offsets[65] VJO_DATA_TABLE(deinflect_offsets) = {"])
    for i in range(0, len(offsets_table), 16):
        lines.append("    " + ", ".join(map(str, offsets_table[i:i + 16])) + ",")
    return "\n".join([*lines, "};", ""])


def generate_labels():
    labels = ["", *rule_sets()]
    lines = ["/* Generated by tools/gen_deinflect.py; see third_party/yomichan/README.md. */",
             "static const char conjugation_labels[] VJO_DATA_TABLE(conjugation_labels) ="]
    offsets, size = [], 0
    for label in labels:
        offsets.append(size)
        size += len(label.encode()) + 1
        lines.append("    " + json.dumps(label + "\0").replace("\\u0000", "\\0"))
    lines.extend([";", "static const uint16_t conjugation_offsets[] VJO_DATA_TABLE(conjugation_offsets) = {",
                  "    " + ", ".join(map(str, offsets)), "};", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    (ROOT / "core/deinflect.inc").write_text(generate(), encoding="utf-8")
    (ROOT / "core/conjugation.inc").write_text(generate_labels(), encoding="utf-8")
