#!/usr/bin/env python3
"""The MAGES/5pb. SC3 charsets of Rubi's SC3 hooks (docs/native-hooks.md, "SC3 text"): each game's glyph index ->
character table as the file the game worker reads, third_party/sc3-charsets/<title>.sc3, and the pins of those
files that the worker accepts, core/hook_sc3_pins.inc.

The tables come from the bee-san/psandvita farm: hooks/vita/<title>/sc3-charset.json (schema vn-sc3-charset/1:
"charset", a list whose index is the glyph's, each one character or null for a glyph the table cannot name) and the
module NID of the same directory's rubi-hook.json. third_party/sc3-charsets/README.md records where each table comes
from, its licences and its checks.

    python3 tools/sc3_charset.py --farm DIR TITLE...   # DIR/<TITLE>/ -> third_party/sc3-charsets/<TITLE>.sc3, the pins
    python3 tools/sc3_charset.py --check               # the committed files and pins: exits 1 when one is wrong
    python3 tools/sc3_charset.py --fixtures RUN...     # host/tests/fixtures/hook_sc3_farm.inc from the farm's runs

--fixtures reads each paired run's approved pages (RUN/samples/*.json: the bytes the hook read, raw_hex, and the text
the farm verified against the frame the game drew) and writes a few short ones per title that the committed charset
decodes to exactly that text (decode(), the C decoder's rules, with the farm's <base,reading> form for ruby), with the
text in Rubi's form (ruby's base only), chosen to cover the tokens of the game's strings.

A file (core/hook_sc3.h): a 32-byte header, b"vjosc3\\x00\\x01", the title ID NUL-padded to 12 bytes, the main
module's NID and the glyph count (little-endian 32-bit), 4 zero bytes; then each glyph's character as a
little-endian 16-bit code point, 0 for null. Every character must be one code point of the BMP, neither a
surrogate nor U+0000; at most 16,384 bytes (VJO_SC3_MAX_BYTES). Standard library only; the output is deterministic.
"""
import argparse
import hashlib
import json
import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = ROOT / "third_party" / "sc3-charsets"
PINS = ROOT / "core" / "hook_sc3_pins.inc"
MAGIC = b"vjosc3\x00\x01"
HEADER = 32
MAX_BYTES = 16384  # core/hook_sc3.h VJO_SC3_MAX_BYTES
SCHEMA = "vn-sc3-charset/1"
TITLE = re.compile(r"[A-Z]{4}[0-9]{5}")


def code_point(char, title, index):
    """The 16-bit code point of a charset entry (0 for null); ValueError for anything else."""
    if char is None:
        return 0
    if not isinstance(char, str) or len(char) != 1:
        raise ValueError(f"{title}: glyph {index} is {char!r}, not one character")
    cp = ord(char)
    if not 0 < cp <= 0xFFFF or 0xD800 <= cp <= 0xDFFF:
        raise ValueError(f"{title}: glyph {index} is U+{cp:04X}, not a BMP character")
    return cp


def build(title, charset, module_nid):
    """The .sc3 file's bytes."""
    if not TITLE.fullmatch(title):
        raise ValueError(f"{title!r} is not a title ID")
    table = [code_point(c, title, i) for i, c in enumerate(charset)]
    data = (MAGIC + title.encode("ascii").ljust(12, b"\0") + struct.pack("<III", module_nid, len(table), 0) +
            struct.pack(f"<{len(table)}H", *table))
    if len(data) > MAX_BYTES:
        raise ValueError(f"{title}: {len(data)} B, over the worker's {MAX_BYTES} B")
    return data


def parse(data, name):
    """(title, module NID, count) of a .sc3 file's bytes; ValueError when its header is not what build() writes."""
    if len(data) < HEADER or data[:8] != MAGIC:
        raise ValueError(f"{name}: not an SC3 charset file")
    title = data[8:20].rstrip(b"\0").decode("ascii", "replace")
    nid, count, zero = struct.unpack_from("<III", data, 20)
    if not TITLE.fullmatch(title) or data[8:20] != title.encode("ascii").ljust(12, b"\0") or zero:
        raise ValueError(f"{name}: a bad header")
    if len(data) != HEADER + 2 * count or len(data) > MAX_BYTES:
        raise ValueError(f"{name}: {len(data)} B for {count} glyphs")
    for i, (cp,) in enumerate(struct.iter_unpack("<H", data[HEADER:])):
        if 0xD800 <= cp <= 0xDFFF:
            raise ValueError(f"{name}: glyph {i} is a surrogate")
    return title, nid, count


def pins_text(files):
    """core/hook_sc3_pins.inc for {title: bytes}."""
    lines = ["/* Generated by tools/sc3_charset.py from the files in third_party/sc3-charsets: do not edit. The",
             " * charset files the game worker accepts (core/hook_sc3.h VjoSc3Pin): each one's size and SHA-256. */",
             "static const VjoSc3Pin sc3_pins[] VJO_DATA_TABLE(sc3_pins) = {"]
    for title in sorted(files):
        data = files[title]
        digest = hashlib.sha256(data).digest()
        hexes = ", ".join(f"0x{b:02X}" for b in digest)
        lines.append(f'    {{"{title}", {len(data)}u,')
        lines.append(f"     {{{hexes[:96].rstrip(', ')},")
        lines.append(f"      {hexes[96:].strip()}}}}},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def tokens(raw):
    """(kind, value, start, end) of an SC3 string's tokens through its end token (core/hook_sc3.c token()); ValueError
    when there is no end token or one is cut."""
    i = 0
    while i < len(raw):
        c = raw[i]
        if c == 0xFF:
            yield ("end", c, i, i + 1)
            return
        k = i + 1
        if c >= 0x80:
            k += 1
        elif c in (0x0C, 0x11, 0x12, 0x13):
            k += 2
        elif c in (0x04, 0x15):
            while True:
                if k >= len(raw):
                    raise ValueError("an expression cut")
                t = raw[k]
                if not t:
                    break
                k += 2 + ((t & 0x60) >> 5) if t & 0x80 else 2
            k += 1
        if k > len(raw):
            raise ValueError("a token cut")
        yield ("glyph", (c & 0x7F) << 8 | raw[i + 1], i, k) if c >= 0x80 else ("control", c, i, k)
        i = k
    raise ValueError("no end token")


def decode(raw, table, farm=False):
    """The text of an SC3 string by core/hook_sc3.c's rules: a glyph its table entry (0, or past the table: dropped;
    with farm=True a ValueError, as the farm's strict codec), 0x00 a line break, a name (0x01..0x02) on its own line,
    ruby's base only; farm=True writes ruby as the farm does, <base,reading>."""
    out, name, reading = [], False, False
    for kind, value, _, _ in tokens(raw):
        if kind == "end":
            break
        if kind == "glyph":
            cp = table[value] if value < len(table) else 0
            if farm and not cp:
                raise ValueError(f"glyph {value:#x} has no character")
            if cp and (farm or not reading):
                out.append(chr(cp))
        elif value == 0x00:
            out.append("\n")
        elif value == 0x01:
            name = True
        elif value == 0x02:
            if name:
                out.append("\n")
            name = False
        elif value == 0x09 and farm:
            out.append("<")
        elif value == 0x0A:
            reading = True
            if farm:
                out.append(",")
        elif value == 0x0B:
            reading = False
            if farm:
                out.append(">")
    return "".join(out)


def features(raw):
    """What an excerpt shows of the decoder: its controls and the glyphs whose low byte is 0x00 or 0xFF."""
    out = set()
    for kind, value, start, end in tokens(raw):
        if kind == "glyph" and raw[start + 1] in (0x00, 0xFF):
            out.add(f"glyph-{raw[start + 1]:02x}")
        elif kind == "control":
            out.add(f"control-{value:02x}" if value in (0x00, 0x01, 0x02, 0x09, 0x0A, 0x0B, 0x04, 0x15) else
                    "control-args" if value in (0x0C, 0x11, 0x12, 0x13) else "control-other")
    return out


def c_bytes(data):
    return "".join(f"\\x{b:02X}" for b in data)


def cmd_fixtures(runs, out_path, max_bytes=128, per_title=5):
    """host/tests/fixtures/hook_sc3_farm.inc: per title, at most per_title of its approved single-hit pages of at
    most max_bytes, the most new features per byte first."""
    files = committed()
    rows = []
    for run in runs:
        cands, title = [], None
        for path in sorted((run / "samples").glob("*.json")):
            page = json.loads(path.read_text(encoding="utf-8"))
            events = page.get("raw_text_events") or []
            title = page.get("title_id") or title
            if len(events) != 1 or title not in files:
                continue
            raw = bytes.fromhex(events[0]["raw_hex"])
            data = files[title]
            table = [v for (v,) in struct.iter_unpack("<H", data[HEADER:])]
            try:
                if len(raw) > max_bytes or decode(raw, table, farm=True) != page["text"]:
                    continue
                text = decode(raw, table)
            except ValueError:
                continue
            span = next(e for k, _, _, e in tokens(raw) if k == "end")
            cands.append((path.stem, raw[:span], text, features(raw)))
        pick, have = [], set()
        while len(pick) < per_title:
            best, score = None, 0.0
            for k, (_, raw, _, feats) in enumerate(cands):
                new = len(feats - have)
                sc = (new + 0.01) / (len(raw) + 8)
                if k not in pick and (new and sc > score or (best is None and not new and not pick)):
                    best, score = k, sc
            if best is None:
                break
            pick.append(best)
            have |= cands[best][3]
        for k in pick:
            page, raw, text, feats = cands[k]
            rows.append(f'    {{"{title}", "{c_bytes(raw)}", {len(raw)}, "{c_bytes(text.encode("utf-8"))}"}}, '
                        f'/* page {page}: {", ".join(sorted(feats)) or "glyphs"} */')
    head = ["/* Generated by tools/sc3_charset.py --fixtures from the psandvita farm's approved pages: per SC3 title, a",
            " * few short hits (the bytes its hook read at the page function's r0, through the string's 0xFF end token)",
            " * and the text the farm verified against the frame the game drew, with ruby's base only (Rubi's form).",
            " * Short excerpts only, never a script. Do not edit: regenerate. */",
            "#define HOOK_SC3_FARM_ROWS \\"]
    text = "\n".join(head) + "\n" + " \\\n".join(rows) + f"\n#define HOOK_SC3_FARM_FIXTURES {len(rows)}\n"
    out_path.write_text(text, encoding="utf-8")
    return len(rows)


def committed():
    """{title: bytes} of the committed files, each checked."""
    out = {}
    for path in sorted(FILES.glob("*.sc3")):
        data = path.read_bytes()
        title, _, _ = parse(data, path.name)
        if path.name != title + ".sc3":
            raise ValueError(f"{path.name}: its header names {title}")
        out[title] = data
    return out


def from_farm(farm, title):
    """The .sc3 bytes of a title from the farm's directory (DIR/<title>/sc3-charset.json and rubi-hook.json)."""
    source = json.loads((farm / title / "sc3-charset.json").read_text(encoding="utf-8"))
    hook = json.loads((farm / title / "rubi-hook.json").read_text(encoding="utf-8"))
    if source.get("schema") != SCHEMA or source.get("title_id") != title or hook.get("title") != title:
        raise ValueError(f"{title}: not a {SCHEMA} charset of {title}")
    if source.get("charset_length", len(source["charset"])) != len(source["charset"]):
        raise ValueError(f"{title}: charset_length is not the charset's")
    return build(title, source["charset"], int(hook["module_nid"], 16))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--farm", type=pathlib.Path, help="the farm's hooks/vita directory")
    parser.add_argument("--check", action="store_true", help="check the committed files and pins")
    parser.add_argument("--fixtures", action="store_true", help="write the host tests' farm excerpts from the runs")
    parser.add_argument("titles", nargs="*", help="the titles (--farm), or the farm's paired runs (--fixtures)")
    args = parser.parse_args()
    if args.check + bool(args.farm) + args.fixtures != 1 or (not args.check and not args.titles):
        parser.error("give --check, --farm DIR and the titles, or --fixtures and the runs")
    try:
        if args.fixtures:
            n = cmd_fixtures([pathlib.Path(t) for t in args.titles], ROOT / "host/tests/fixtures/hook_sc3_farm.inc")
            print(f"sc3_charset: {n} excerpts")
            return 0
        if args.farm:
            FILES.mkdir(parents=True, exist_ok=True)
            for title in args.titles:
                data = from_farm(args.farm, title)
                (FILES / (title + ".sc3")).write_bytes(data)
                print(json.dumps({"title": title, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}))
            PINS.write_text(pins_text(committed()), encoding="utf-8")
            return 0
        files = committed()
        if not files:
            raise ValueError("no third_party/sc3-charsets/*.sc3")
        if PINS.read_text(encoding="utf-8") != pins_text(files):
            raise ValueError("core/hook_sc3_pins.inc is not the files' pins: run tools/sc3_charset.py --farm")
    except (OSError, ValueError, KeyError) as e:
        print(f"sc3_charset: {e}", file=sys.stderr)
        return 1
    print(f"sc3_charset: {len(files)} charsets and their pins agree")
    return 0


if __name__ == "__main__":
    sys.exit(main())
