"""Generate core/hook_luna_psp.inc (LunaTranslator's PSP hook table, only each site's address and
title IDs, for the debug build's read-only PSP probe, core/psp_probe.c) from the vendored,
unmodified LunaTranslator 51884b6 ppsspp_1.cpp in third_party/LunaTranslator/ (GPL-3.0).

    python3 tools/gen_luna_psp.py           # writes core/hook_luna_psp.inc
    python3 tools/gen_luna_psp.py --check   # exits 1 if it is stale
    python3 tools/gen_luna_psp.py --counts  # prints the table's counts

What it reads, with tools/gen_luna_vita.py's pinned reader and parser (the same SHA-256 pin,
third_party/LunaTranslator/README.md): ppsspp_1.cpp's emfunctionhooks_1 table, an entry per line,
    {addr, {type, offset, padding, hookfunc, filterfun, "ID" | std::vector{"ID", ...}}}, // comment
where addr is a PPSSPP guest address (the game's main module at 0x08804000, docs/native-hooks.md
"PSP probe (debug build)"). Luna loads the table into an unordered_map with emplace
(ppsspp_1.cpp ppsspp_load_functions), so of two entries with the same address only the first is
used; this pin has none. Kept per entry: its address and its title IDs, nothing else (the probe
logs raw words; which register or encoding a site reads is in Luna's source, by address).

Output: the title IDs sorted, each title's sites together in the table's order. Standard library
only; the output is deterministic (Python 3.9 or later).
"""
import argparse
import collections
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_luna_vita as luna  # noqa: E402  (the pin, its SHA-256 check and the table parser)

ROOT = luna.ROOT
OUT = ROOT / "core" / "hook_luna_psp.inc"
MARKER = "emfunctionhooks_1[] = {"
IDS_PER_LINE = 8
ADDRS_PER_LINE = 6


def table():
    """(entries, sites): Luna's entries in source order (the first of an address only), and the
    sites as {id: [addresses, in the table's order]}."""
    entries, seen = [], set()
    for e in luna.parse_table(luna.read_pinned("ppsspp_1.cpp"), MARKER):
        if e["addr"] in seen:
            continue  # emplace: an earlier entry has this address
        seen.add(e["addr"])
        entries.append(e)
    sites = collections.OrderedDict()
    for e in entries:
        for i in e["ids"]:
            sites.setdefault(i, [])
            if e["addr"] not in sites[i]:
                sites[i].append(e["addr"])
    return entries, collections.OrderedDict(sorted(sites.items()))


def counts():
    entries, sites = table()
    n_sites = sum(len(a) for a in sites.values())
    return {
        "entries": len(entries),
        "addresses": len({e["addr"] for e in entries}),
        "titles": len(sites),
        "sites": n_sites,
        "multi_id_entries": sum(1 for e in entries if len(e["ids"]) > 1),
        "max_sites_per_title": max(len(a) for a in sites.values()),
        "titles_with_2_or_more": sum(1 for a in sites.values() if len(a) >= 2),
        "min_addr": min(e["addr"] for e in entries),
        "max_addr": max(e["addr"] for e in entries),
        "bytes": len(sites) * 9 + 1 + len(sites) + 4 * n_sites,
    }


def render_inc():
    entries, sites = table()
    c = counts()
    ids = list(sites)
    out = [
        "/* Generated by tools/gen_luna_psp.py from third_party/LunaTranslator/ppsspp_1.cpp",
        f" * (HIllya51/LunaTranslator {luna.LUNA_COMMIT[:7]}, {luna.LUNA_VERSION}, GPL-3.0): its emfunctionhooks_1 PSP",
        " * table, each entry's PPSSPP address and title IDs only, for the debug build's PSP probe",
        " * (core/psp_probe.c). Do not edit: change the generator. */",
        f"/* {c['entries']} entries ({c['addresses']} addresses), {c['titles']} title IDs, {c['sites']} sites (one per address"
        f" and title: {c['multi_id_entries']} entries name several IDs); at most {c['max_sites_per_title']} sites per title;"
        f" {c['bytes']:,} bytes. */",
        f"#define VJO_LUNA_PSP_ENTRIES {c['entries']}u",
        f"#define VJO_LUNA_PSP_TITLES {c['titles']}u",
        f"#define VJO_LUNA_PSP_SITES {c['sites']}u",
        f"#define VJO_LUNA_PSP_SITES_PER_TITLE_MAX {c['max_sites_per_title']}u",
        "",
        "/* The title IDs, sorted, 9 characters each, one after another (one NUL at the end) */",
        "static const char vjo_luna_psp_ids[VJO_LUNA_PSP_TITLES * 9u + 1u] =",
    ]
    for k in range(0, len(ids), IDS_PER_LINE):
        chunk = " ".join(f'"{i}"' for i in ids[k:k + IDS_PER_LINE])
        out.append(f"    {chunk}{';' if k + IDS_PER_LINE >= len(ids) else ''}")
    out += ["", "/* Each title's number of sites, in the IDs' order */",
            "static const uint8_t vjo_luna_psp_count[VJO_LUNA_PSP_TITLES] = {"]
    counts_list = [len(sites[i]) for i in ids]
    for k in range(0, len(counts_list), 24):
        out.append("    " + ", ".join(str(n) for n in counts_list[k:k + 24]) + ",")
    out += ["};", "",
            "/* The sites' PPSSPP addresses: each title's together, in the IDs' order, a title's in the table's order */",
            "static const uint32_t vjo_luna_psp_addr[VJO_LUNA_PSP_SITES] = {"]
    for i in ids:
        addrs = sites[i]
        for k in range(0, len(addrs), ADDRS_PER_LINE):
            row = ", ".join(f"0x{a:08X}u" for a in addrs[k:k + ADDRS_PER_LINE])
            out.append(f"    {row}, /* {i} */" if k == 0 else f"    {row},")
    out += ["};", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the .inc is stale")
    ap.add_argument("--counts", action="store_true", help="print the table's counts")
    ap.add_argument("-o", "--output", type=pathlib.Path, default=OUT)
    args = ap.parse_args()
    if args.counts:
        for k, v in counts().items():
            print(f"{k}: {v:#010x}" if k.endswith("_addr") else f"{k}: {v}")
        return
    text = render_inc()
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != text:
            sys.exit(f"stale: {args.output}: run python3 tools/gen_luna_psp.py")
        return
    args.output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
