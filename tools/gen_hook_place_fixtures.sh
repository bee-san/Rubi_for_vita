#!/usr/bin/env bash
# Assembles every instruction form in tools/hook_place_forms.txt with the VitaSDK assembler into
# host/tests/fixtures/hook_place_forms.inc, the byte fixtures of host/tests/test_hook_place.c (the
# native hooks' site check, core/hook_place.c). Run it where VitaSDK is installed (VITASDK, default
# /usr/local/vitasdk; e.g. the vitasdk/vitasdk image) after changing the forms list, and commit both.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
VITASDK=${VITASDK:-/usr/local/vitasdk}
AS="$VITASDK/bin/arm-vita-eabi-as"
OBJCOPY="$VITASDK/bin/arm-vita-eabi-objcopy"
in="$root/tools/hook_place_forms.txt"
out="$root/host/tests/fixtures/hook_place_forms.inc"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

{
    echo "/* Generated by tools/gen_hook_place_fixtures.sh from tools/hook_place_forms.txt"
    echo " * with $("$AS" --version | head -n 1) (-march=armv7-a -mfpu=neon). Do not edit."
    echo " * { thumb, expected ok, entry (else inside the window), bytes, length, source } */"
    while read -r isa expect role src; do
        case "$isa" in '' | '#'*) continue ;; esac
        case "$isa" in thumb) mode=.thumb t=1 ;; arm) mode=.arm t=0 ;; *) echo "bad isa: $isa" >&2; exit 1 ;; esac
        case "$expect" in ok) e=1 ;; no) e=0 ;; *) echo "bad expected: $expect" >&2; exit 1 ;; esac
        case "$role" in entry) r=1 ;; win) r=0 ;; *) echo "bad role: $role" >&2; exit 1 ;; esac
        printf '.syntax unified\n%s\n%s\n' "$mode" "$(printf '%s' "$src" | tr ';' '\n')" > "$tmp/f.s"
        "$AS" -march=armv7-a -mfpu=neon -o "$tmp/f.o" "$tmp/f.s"
        "$OBJCOPY" -O binary -j .text "$tmp/f.o" "$tmp/f.bin"
        n=$(wc -c < "$tmp/f.bin" | tr -d ' ')
        if [ "$n" -lt 2 ] || [ "$n" -gt 12 ]; then echo "form '$src': $n bytes" >&2; exit 1; fi
        bytes=$(od -An -v -tx1 "$tmp/f.bin" | tr -s ' \n' ' ' | sed 's/^ //; s/ $//; s/\([0-9a-f][0-9a-f]\)/0x\1,/g; s/,$//')
        printf '{%d, %d, %d, {%s}, %d, "%s"},\n' "$t" "$e" "$r" "$bytes" "$n" "$src"
    done < "$in"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out ($(grep -c '^{' "$out") forms)"
