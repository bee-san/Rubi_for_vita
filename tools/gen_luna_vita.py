def read_pinned(name):
    data = (SRC / name).read_bytes()
    got = hashlib.sha256(data).hexdigest()
    if got != PINNED[name]:
        sys.exit(f"{SRC / name}: SHA-256 {got}, expected {PINNED[name]} (third_party/LunaTranslator/README.md)")
    return data.decode("utf-8")


def split_top(s):
    """Splits on commas outside <...>, (...), {...} and string literals."""
    out, depth, cur, quote = [], 0, "", False
    for ch in s:
        if quote:
            cur += ch
            if ch == '"':
                quote = False
            continue
        if ch == '"':
            quote = True
        elif ch in "<({":
            depth += 1
        elif ch in ">)}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def parse_table(text, marker):
    """The entries of a Luna emfunctionhooks_1 table, in source order. A run of comment lines
    (after a blank line or an entry) heads the entries after it: a game's block."""
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if marker in l)
    entries, headers, in_block, block = [], [], False, -1
    for i in range(start + 1, len(lines)):
        raw = lines[i]
        s = raw.strip()
        if s.startswith("};"):
            break
        if in_block:
            in_block = "*/" not in s
            continue
        if s.startswith("/*"):
            in_block = "*/" not in s
            headers = []
            continue
        if not s:
            headers = []  # a blank line ends a run of header comments
            continue
        if s.startswith("//"):
            headers.append(s[2:].strip())
            continue
        m = ENTRY_RE.match(raw)
        if not m:
            sys.exit(f"line {i + 1}: not an entry: {raw!r}")
        parts = split_top(m.group(2))
        if len(parts) != 6:
            sys.exit(f"line {i + 1}: {len(parts)} fields: {raw!r}")
        ids = re.findall(r'"([^"]+)"', parts[5])
        if not ids or any(not ID_RE.match(x) for x in ids):
            sys.exit(f"line {i + 1}: title IDs {parts[5]!r}")
        if headers or block < 0:
            block += 1
        entries.append({
            "line": i + 1, "addr": int(m.group(1), 16), "type": parts[0], "offset": int(parts[1], 0),
            "padding": int(parts[2], 0), "func": parts[3], "filter": parts[4], "ids": ids,
            "comment": m.group(3) or "", "headers": list(headers), "block": block,
        })
        headers = []
    return entries


def flags_of(type_expr):
    toks = {t.strip() for t in type_expr.split("|")}
    known = {"0", "FULL_STRING", "CODEC_UTF8", "CODEC_UTF16", "USING_CHAR", "DATA_INDIRECT"}
    if toks - known:
        sys.exit(f"unknown hook type {type_expr!r}")
    enc = "UTF16" if "CODEC_UTF16" in toks else "UTF8" if "CODEC_UTF8" in toks else "CP932"
    flags = [f for f in ("USING_CHAR", "DATA_INDIRECT", "FULL_STRING") if f in toks]
    return enc, flags


def version_of(comment):
    m = VERSION_RE.match(comment.strip())
    if not m:
        return 0
    return int(m.group(1), 16) << 8 | int(m.group(2), 16)


def ver_text(v):
    return "%x.%02x" % (v >> 8, v & 0xFF) if v else ""


def names_of(entries):
    """Each title ID's game names, from the header comments (a "NAME //ID" comment names ID)."""
    names = collections.defaultdict(list)
    for e in entries:
        hs = e["headers"]
        tagged = [h for h in hs if re.search(r"//\s*[A-Z]{4}\d{5}\s*$", h)]
        for h in tagged:
            nm, tid = re.match(r"^(.*?)\s*//\s*([A-Z]{4}\d{5})\s*$", h).groups()
            if nm and nm not in names[tid]:
                names[tid].append(nm)
        plain = [h for h in hs if h not in tagged]
        for tid in e["ids"]:
            for h in plain:
                if h not in names[tid]:
                    names[tid].append(h)
    return names


def block_names(entries):
    """The name of each entry's block (its header comment, or the block's)."""
    cur, out = "", {}
    for e in entries:
        hs = [re.sub(r"\s*//\s*[A-Z]{4}\d{5}\s*$", "", h) for h in e["headers"]]
        if hs:
            cur = " / ".join(dict.fromkeys(h for h in hs if h))
        out[e["line"]] = cur
    return out


def vita_sites():
    text = read_pinned("vita3k_1.cpp")
    entries = parse_table(text, "emfunctionhooks_1[] = {")
    bnames = block_names(entries)
    # versions: a comment's version holds for its entry and the later ones of its block
    cur_block, cur_ver = None, 0
    for e in entries:
        if e["block"] != cur_block:
            cur_block, cur_ver = e["block"], 0
        v = version_of(e["comment"])
        if v:
            cur_ver = v
        e["version"] = cur_ver
    first_at = {}
    sites, dropped = [], []
    for e in entries:
        enc, flags = flags_of(e["type"])
        func = e["func"] if e["func"] != "0" else ""
        filt = e["filter"] if e["filter"] != "0" else ""
        if func and func not in FUNCS:
            sys.exit(f"line {e['line']}: hookfunc {func} is not in FUNCS")
        if filt and filt not in FILTERS:
            sys.exit(f"line {e['line']}: filterfun {filt} is not in FILTERS")
        owner = first_at.setdefault(e["addr"], e)
        for tid in dict.fromkeys(e["ids"]):  # an ID listed twice in one entry is one site
            if owner is not e and tid in owner["ids"]:
                dropped.append((e, tid, owner))
                continue
            reasons = []
            if owner is not e:
                reasons.append("shadowed: Luna's map keeps the first entry for 0x%08X (line %d, %s), so it never "
                               "used this one" % (e["addr"], owner["line"], ", ".join(owner["ids"])))
            if "USING_CHAR" in flags:
                reasons.append("USING_CHAR: one character per hit, which Luna's text thread joins into a sentence "
                               "across hits")
            if func and not FUNCS[func][1]:
                reasons.append("hookfunc %s: %s" % (func, FUNCS[func][2]))
            if filt and not FILTERS[filt][1]:
                reasons.append("filter %s: %s" % (filt, FILTERS[filt][2]))
            note = e["comment"] if not version_of(e["comment"]) else ""
            sites.append({
                "id": tid, "addr": e["addr"], "padding": e["padding"], "reg": e["offset"], "enc": enc,
                "flags": flags, "func": func, "filter": filt, "version": e["version"], "line": e["line"],
                "ported": not reasons, "reasons": reasons, "game": bnames[e["line"]], "note": note,
            })
    for s in sites:
        if not 0 <= s["reg"] <= 15:
            sys.exit(f"line {s['line']}: register {s['reg']}")
        if s["addr"] < SEG0:
            sys.exit(f"line {s['line']}: address below VJO_LUNA_SEG0")
        s["guest"] = (s["id"], s["addr"]) in GUEST_SITES
        if s["guest"] and s["addr"] < GUEST_SEG0:
            sys.exit(f"line {s['line']}: GUEST_SITES lists 0x{s['addr']:08X}, below VJO_LUNA_GUEST_SEG0")
    for key in GUEST_SITES:  # every listed site is in the table, once
        if sum((s["id"], s["addr"]) == key for s in sites) != 1:
            sys.exit("GUEST_SITES: %s 0x%08X is not one site of the table" % key)
    titles = sorted({s["id"] for s in sites})
    index = {t: i for i, t in enumerate(titles)}
    order = sorted(range(len(sites)), key=lambda k: (index[sites[k]["id"]], k))
    sites = [sites[k] for k in order]
    for s in sites:
        s["title"] = index[s["id"]]
    return entries, sites, titles, dropped, names_of(entries)


