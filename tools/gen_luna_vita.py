def kana_map():
    """Luna's katakanaMap (stringfilters.cpp): the half-width katakana block U+FF61-U+FF9F in
    order, and the other pairs."""
    text = read_pinned("stringfilters.cpp")
    m = re.search(r"katakanaMap = \{(.*?)\};", text, re.S)
    pairs = [(ord(a), ord(b)) for a, b in re.findall(r"\{L'(.)', L'(.)'\}", m.group(1))]
    block = dict(p for p in pairs if 0xFF61 <= p[0] <= 0xFF9F)
    if sorted(block) != list(range(0xFF61, 0xFFA0)):
        sys.exit("stringfilters.cpp: katakanaMap no longer maps the whole half-width katakana block")
    return [block[c] for c in range(0xFF61, 0xFFA0)], [p for p in pairs if not 0xFF61 <= p[0] <= 0xFF9F]


