static char logs[4096];
void vjo_log(const char *fmt, ...)
{
    va_list ap;
    size_t n = strlen(logs);
    va_start(ap, fmt);
    vsnprintf(logs + n, sizeof(logs) - n - 1, fmt, ap);
    va_end(ap);
    n = strlen(logs);
    if (n + 1 < sizeof(logs)) {
        logs[n] = '\n';
        logs[n + 1] = '\0';
    }
}

#if defined(__GLIBC__)
/* libjpeg's memory: malloc and free while a decode runs (glibc's own allocator underneath). */
extern void *__libc_malloc(size_t);
extern void __libc_free(void *);
static int tracking;
static size_t heap_now, heap_peak;
void *malloc(size_t n)
{
    void *p = __libc_malloc(n);
    if (p && tracking) {
        heap_now += malloc_usable_size(p);
        if (heap_now > heap_peak)
            heap_peak = heap_now;
    }
    return p;
}
void free(void *p)
{
    if (p && tracking)
        heap_now -= malloc_usable_size(p);
    __libc_free(p);
}
#endif

/* The screenshot: a gradient with dark strokes (test_apkg.c's), 960 x 544. */
static int rows(void *ud, uint32_t row, uint32_t n, uint8_t *dst)
{
    uint32_t w = *(const uint32_t *)ud;
    for (uint32_t r = 0; r < n; r++)
        for (uint32_t x = 0; x < w; x++) {
            uint8_t *p = dst + (r * w + x) * 4u;
            uint32_t y = row + r, ink = y > 380 && y < 520 && (x / 3) % 9 < 2 && (y / 6) % 5 < 4;
            p[0] = (uint8_t)(ink ? 25 : 180 + x * 60 / 960);
            p[1] = (uint8_t)(ink ? 25 : 160 + y * 80 / 544);
            p[2] = (uint8_t)(ink ? 25 : 200 - x * 80 / 960);
            p[3] = 0xFF;
        }
    return (int)n;
}
static uint8_t enc_mem[1024 * 1024];
static size_t screenshot(uint32_t w, uint32_t h, const uint8_t **out)
{
    VjoArena a;
    VjoBuf b;
    vjo_arena_init(&a, enc_mem, sizeof(enc_mem));
    TEST_ASSERT(vjo_jpeg_encode(&a, w, h, w * 4, rows, &w, 70, &b) == 0);
    *out = b.data;
    return b.len;
}

