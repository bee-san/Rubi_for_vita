/* A screenshot into the Cards page's box (416 x 234): 4/8, 480 x 272, its stride a texture's (width to 8, three
 * bytes a pixel); each pixel near the picture's average of the 2 x 2 it covers. */
static void a_screenshot_is_scaled_to_cover_its_box(void)
{
    const uint8_t *jpeg;
    size_t len = screenshot(960, 544, &jpeg);
    VjoCardPixels px;
    long worst = 0, total = 0, n = 0;
    vjo_arena_init(&A, mem, sizeof(mem));
#if defined(__GLIBC__)
    tracking = 1;
#endif
    TEST_ASSERT(vjo_card_picture_decode(&A, jpeg, len, 416, 234, &px) == 0);
#if defined(__GLIBC__)
    tracking = 0;
    printf("measure: libjpeg's heap at most %zu B for a %zu B screenshot shown at %ux%u; %zu B kept after\n", heap_peak,
           len, px.width, px.height, heap_now);
    TEST_CHECK(heap_now == 0);
#endif
    TEST_CHECK(px.width == 480 && px.height == 272 && px.stride == 480 * 3 && px.rgb == mem &&
               A.used >= (size_t)px.stride * px.height);
    for (unsigned y = 0; y < px.height; y += 7)
        for (unsigned x = 0; x < px.width; x += 5) {
            static uint8_t line[2][960 * 4]; /* the picture's two rows this pixel covers */
            uint32_t w = 960;
            int want[3] = {0, 0, 0};
            rows(&w, 2 * y, 1, line[0]);
            rows(&w, 2 * y + 1, 1, line[1]);
            for (int c = 0; c < 3; c++) {
                for (int k = 0; k < 4; k++)
                    want[c] += line[k / 2][(2 * x + k % 2) * 4 + c];
                want[c] /= 4;
            }
            for (int c = 0; c < 3; c++) {
                long d = labs((long)px.rgb[(size_t)y * px.stride + x * 3 + c] - want[c]);
                total += d;
                n++;
                if (d > worst)
                    worst = d;
            }
        }
    /* (a quality 70 JPEG of sharp strokes: the strokes' edges differ most) */
    TEST_CHECK_(total / n <= 6 && worst <= 120, "mean %ld, worst %ld", total / n, worst);
    TEST_MSG("mean difference %ld, worst %ld", total / n, worst);
}

/* A box larger than the picture: the largest scale that fits 512 x 288; a small picture at its own size. */
static void the_size_stays_within_the_texture(void)
{
    const uint8_t *jpeg;
    size_t len = screenshot(960, 544, &jpeg);
    VjoCardPixels px;
    vjo_arena_init(&A, mem, sizeof(mem));
    TEST_ASSERT(vjo_card_picture_decode(&A, jpeg, len, 2000, 2000, &px) == 0);
    TEST_CHECK(px.width == 480 && px.height == 272);
    len = screenshot(100, 60, &jpeg);
    vjo_arena_init(&A, mem, sizeof(mem));
    TEST_ASSERT(vjo_card_picture_decode(&A, jpeg, len, 416, 234, &px) == 0);
    TEST_CHECK(px.width == 100 && px.height == 60 && px.stride == 104 * 3);
}

/* A grey JPEG: three bytes a pixel, R = G = B. */
static void a_grey_picture_is_rgb(void)
{
    VjoCardPixels px;
    vjo_arena_init(&A, mem, sizeof(mem));
    TEST_ASSERT(vjo_card_picture_decode(&A, grey, sizeof(grey), 416, 234, &px) == 0);
    TEST_CHECK(px.width == 40 && px.height == 24 && px.stride == 40 * 3);
    for (unsigned x = 0; x < px.width; x++) {
        const uint8_t *p = px.rgb + 10 * px.stride + x * 3;
        TEST_CHECK_(p[0] == p[1] && p[1] == p[2] && abs(p[0] - (40 + (int)x * 4)) <= 6, "x %u: %u %u %u", x, p[0],
                    p[1], p[2]);
    }
}

/* A progressive file (its coefficient arrays within VJO_CARD_PICTURE_JPEG_MEM) decodes too. */
static void a_progressive_picture_decodes(void)
{
    VjoCardPixels px;
    vjo_arena_init(&A, mem, sizeof(mem));
    TEST_ASSERT(vjo_card_picture_decode(&A, progressive, sizeof(progressive), 416, 234, &px) == 0);
    TEST_CHECK(px.width == 64 && px.height == 48);
    for (unsigned y = 4; y < px.height; y += 9)
        for (unsigned x = 4; x < px.width; x += 9) {
            const uint8_t *p = px.rgb + y * px.stride + x * 3;
            TEST_CHECK_(abs(p[0] - (int)x * 4) <= 12 && abs(p[1] - (int)y * 5) <= 12 && abs(p[2] - 128) <= 12,
                        "%u,%u: %u %u %u", x, y, p[0], p[1], p[2]);
        }
}

